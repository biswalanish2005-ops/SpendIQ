from typing import List, Optional
from fastapi import APIRouter, Depends, Query, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_db
from app.api.deps import get_current_user
from app.models.user import User
from app.services.forecast_service import ForecastService
from app.schemas.prediction import (
    SpendingForecastResponse,
    SpendingDriver,
    CategoryForecast,
)

router = APIRouter()
forecast_service = ForecastService()


@router.get(
    "/spending",
    response_model=SpendingForecastResponse,
    summary="Get multi-horizon spending forecast with prediction intervals",
)
async def get_spending_forecast(
    horizon_months: int = Query(default=3, ge=1, le=12, description="Forecast horizon in months"),
    confidence_level: float = Query(default=0.80, ge=0.50, le=0.99, description="Confidence interval coverage"),
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Retrieves time-series forecast generated by Holt-Winters exponential smoothing model,
    including empirical prediction intervals, driver decomposition, and category trajectories.
    """
    return await forecast_service.get_or_generate_spending_forecast(
        db=db,
        user_id=current_user.id,
        horizon_months=horizon_months,
        confidence_level=confidence_level,
    )


@router.get(
    "/drivers",
    response_model=List[SpendingDriver],
    summary="Get categorical drivers of projected spending variance",
)
async def get_spending_drivers(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Identifies and ranks categories driving the projected spending changes.
    """
    forecast = await forecast_service.get_or_generate_spending_forecast(
        db=db,
        user_id=current_user.id,
    )
    return forecast.drivers


@router.get(
    "/categories",
    response_model=List[CategoryForecast],
    summary="Get category-level forecast projections",
)
async def get_category_forecasts(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Retrieves projected monthly spend and momentum score per category.
    """
    forecast = await forecast_service.get_or_generate_spending_forecast(
        db=db,
        user_id=current_user.id,
    )
    return forecast.category_forecasts


@router.post(
    "/recompute",
    response_model=SpendingForecastResponse,
    status_code=status.HTTP_200_OK,
    summary="Trigger model re-training and re-forecast",
)
async def recompute_forecast(
    horizon_months: int = Query(default=3, ge=1, le=12),
    confidence_level: float = Query(default=0.80, ge=0.50, le=0.99),
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Executes fresh model fitting across latest database transactions and updates persisted forecast runs.
    """
    return await forecast_service.get_or_generate_spending_forecast(
        db=db,
        user_id=current_user.id,
        horizon_months=horizon_months,
        confidence_level=confidence_level,
        force_recompute=True,
    )
